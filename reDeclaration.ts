// we can re-declare var variables 
var Name = "Programmer Analyst Trainee"
console.log(Name);
var Name = "Programmer Analyst"
console.log(Name);

// for let and const variables we can NOT re-declare the variables
let Name1 = "Programmer Analyst Trainee"
console.log(Name1);
// let Name1 = "Programmer Analyst" --> can not re-declare the variable
//console.log(Name1);

const Name2 = "Programmer Analyst Trainee"
