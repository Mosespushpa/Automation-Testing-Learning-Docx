// for let and var we can re-Assign values
let salary = 26000
console.log("salary ",salary)
salary = 30000
console.log("Salary after exp",salary)

var income = 50000
console.log("income before tax ",income)
income = 45000
console.log("income after tax",income)


// we can NOT Re-Assign values for const variables
const pi = 3.14
console.log(pi)
// pi = 3.147
// console.log(pi) --> const variables can be re-Assigned